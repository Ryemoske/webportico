# ---- Configuración por variables de entorno ----
# En el servidor las da Docker (env_file: .env). En local, si existe un archivo .env junto a
# manage.py, se carga aquí (sin pisar variables ya definidas) para trabajar con DJANGO_DEBUG=True.
_env_local = BASE_DIR / '.env'
if _env_local.exists():
    for _linea in _env_local.read_text(encoding='utf-8-sig').splitlines():
        _linea = _linea.strip()
        if _linea and not _linea.startswith('#') and '=' in _linea:
            _clave, _valor = _linea.split('=', 1)
            os.environ.setdefault(_clave.strip(), _valor.strip().strip('"').strip("'"))


def _env_bool(nombre, defecto=False):
    return os.environ.get(nombre, str(defecto)).strip().lower() in ('1', 'true', 'yes', 'si', 'sí', 'on')


def _env_lista(nombre):
    return [v.strip() for v in os.environ.get(nombre, '').split(',') if v.strip()]


